import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { copyFile, mkdir, mkdtemp, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { performance } from 'node:perf_hooks';
import { Store } from '../src/database/store.ts';
import { Pipeline } from '../src/services/pipeline.ts';
import { exportPhotos, selected } from '../src/services/export.ts';
import type { Progress } from '../src/types/domain.ts';

// Real filesystem/SQLite smoke check, NOT an Electron/AI/photography acceptance test.
await mkdir('.test-tmp', { recursive: true });
const root = await mkdtemp(path.resolve('.test-tmp/real-png-'));
const input = path.join(root, 'input');
await mkdir(input);
const originals = ['ID VISUAL 01.png', 'ID VISUAL 02.png', 'LOGO CLICK IT.png'];
for (const file of originals) await copyFile(file, path.join(input, file));
const hash = async (file: string): Promise<string> => createHash('sha256').update(await readFile(file)).digest('hex');
const originalHashes = await Promise.all(originals.map(file => hash(file)));
const database = path.join(root, 'clickit.sqlite');
let store = new Store(database);
const project = store.create('Validação com os três PNGs reais da marca', input);
const events: Progress[] = [];
const pipeline = new Pipeline({ store, workerFile: path.resolve('dist/analysis.cjs'), groupingFile: path.resolve('dist/grouping.cjs'), cache: path.join(root, 'cache'), model: null, faces: null, concurrency: 1, emit: p => { events.push(p); }, log: () => {} });
let start = performance.now();
await pipeline.index(project.id);
const importMs = performance.now() - start;
const photos = store.photos(project.id);
assert.equal(photos.length, 3);
store.decide(photos[0]!.id, { status: 'SELECTED', favorite: true, rating: 5 });
store.decide(photos[1]!.id, { status: 'REJECTED', rating: 1 });
store.decide(photos[2]!.id, { status: 'REVIEW' });
store.close();
store = new Store(database);
assert.equal(store.project(project.id).count, 3);
assert.equal(store.photo(photos[0]!.id).favorite, true);
assert.equal(store.photo(photos[0]!.id).rating, 5);
assert.equal(store.photo(photos[0]!.id).decision, 'SELECTED');
assert.equal(store.photo(photos[1]!.id).decision, 'REJECTED');
assert.equal(store.photo(photos[2]!.id).decision, 'REVIEW');
const destination = path.join(root, 'export');
start = performance.now();
const result = await exportPhotos(selected(store.photos(project.id)), destination, 'COPY', () => false, () => {});
const exportMs = performance.now() - start;
assert.equal(result.copied, 1);
assert.deepEqual(result.errors, []);
const exported = (await readdir(destination)).filter(name => name.endsWith('.png'));
const sourceHash = await hash(photos[0]!.originalPath);
const destinationHash = await hash(path.join(destination, exported[0]!));
assert.equal(sourceHash, destinationHash);
assert.deepEqual(await Promise.all(originals.map(file => hash(file))), originalHashes);
const sqliteVersion = store.db.prepare('select sqlite_version() version').get()?.version;
store.close();
const evidence = { status: 'PASS_BACKEND_ONLY', scope: '3 PNGs reais da identidade visual; não são um ensaio fotográfico. Sem Electron, thumbnails ou inferência.', root, sqliteVersion, importCount: photos.length, importMs, persistenceAfterReopen: true, rating: 5, favorite: true, rejected: true, exportedOriginals: result.copied, exportMs, sourceHash, destinationHash, originalBrandFilesUnchanged: true, peakNodeRssMiB: process.resourceUsage().maxRSS / 1024, progressEvents: events };
await writeFile('docs/evidence/native-smoke.json', JSON.stringify(evidence, null, 2));
console.log(JSON.stringify(evidence, null, 2));
